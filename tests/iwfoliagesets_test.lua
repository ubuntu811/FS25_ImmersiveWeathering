-- plain Lua: the foliage lists per ground class (IWFoliageSets)
local passed, failed = 0, 0
local function check(name, ok) if ok then passed = passed + 1 else failed = failed + 1; print("  FAIL " .. name) end end
dofile("scripts/IWFoliageSets.lua")
local function sets()
    return IWFoliageSets.new({ meadow = { { name = "decoBush", chance = 1 }, { name = "grassShort", chance = 99 } } })
end
local s = sets()
check("the meadow has the map's list, the other classes are empty", #s:entries("meadow") == 2 and #s:entries("bare") == 0 and #s:entries("forest") == 0)
check("a class that is not seeded has no list", #s:entries("road") == 0 and s:pick("road", function() return 0 end) == nil)
check("the pick follows the chances", s:pick("meadow", function() return 0.005 end) == "decoBush" and s:pick("meadow", function() return 0.5 end) == "grassShort")
check("an empty list seeds nothing", s:pick("bare", function() return 0 end) == nil)
local half = IWFoliageSets.new({ bare = { { name = "weed", chance = 30 } } })
check("what is left of the roll seeds nothing", half:pick("bare", function() return 0.2 end) == "weed" and half:pick("bare", function() return 0.6 end) == nil)

check("toggling adds with the default chance", s:toggle("bare", "weed") == true and s:chanceOf("bare", "weed") == IWFoliageSets.DEFAULT_CHANCE and s:isEdited("bare"))
check("the meadow is not touched by an edit of the bare list", not s:isEdited("meadow") and #s:entries("meadow") == 2)
check("toggling again takes it out", s:toggle("bare", "weed") == false and #s:entries("bare") == 0)
s:toggle("bare", "weed")
check("a chance is set within 0..100", s:setChance("bare", "weed", 250) == 100 and s:setChance("bare", "weed", -4) == 0)
check("a step adds to the chance", s:setChance("bare", "weed", 20) == 20 and s:addChance("bare", "weed", 5) == 25)
check("a chance of something not in the list is nil", s:setChance("bare", "nothing", 5) == nil and s:addChance("bare", "nothing", 5) == nil)

local saved = s:serialize()
check("only the edited lists are written", #saved == 1 and saved[1].key == "bare" and saved[1].entries[1].name == "weed" and saved[1].entries[1].chance == 25)
local t = sets()
t:restore(saved)
check("a restored list replaces the default", t:chanceOf("bare", "weed") == 25 and t:isEdited("bare") and not t:isEdited("meadow"))
local u = IWFoliageSets.new({ meadow = { { name = "newMapFlower", chance = 100 } } })
u:restore({ { key = "bare", builtin = true, edited = true, entries = { { name = "weed", chance = 5 } } } })
check("an untouched list follows the map when the map changes", u:chanceOf("meadow", "newMapFlower") == 100)
t:toggle("meadow", "decoBush")
t:reset("meadow")
check("reset goes back to the map's list", #t:entries("meadow") == 2 and not t:isEdited("meadow") and #t:serialize() == 1)
s:reset("bare")
check("reset empties a class without a default", #s:entries("bare") == 0 and #s:serialize() == 0)
local d = { { name = "a", chance = 5 } }
local w = IWFoliageSets.new({ meadow = d })
w:setChance("meadow", "a", 50)
check("an edit does not change the table the map handed in", d[1].chance == 5)
-- the player's own sets
local p = sets()
local k1 = p:add()
check("a new set is empty, named, the player's, and comes after the three ground sets", p:count() == 4 and p:keyAt(4) == k1 and #p:entries(k1) == 0 and p:get(k1).builtin == false and p:get(k1).name ~= nil)
p:toggle(k1, "aster"); p:setChance(k1, "aster", 40); p:toggle(k1, "decoBush")
check("it is edited like any set", p:chanceOf(k1, "aster") == 40 and p:pick(k1, function() return 0.3 end) == "aster" and p:pick(k1, function() return 0.9 end) == nil)
check("it can be renamed, a ground set cannot", p:rename(k1, "Orchard edge") and p:get(k1).name == "Orchard edge" and not p:rename("meadow", "x") and p:rename(k1, "") == false)
local k2 = p:duplicate(k1)
check("a copy has the same foliage and a name of its own, and does not share the entries", p:count() == 5 and p:chanceOf(k2, "aster") == 40 and p:get(k2).name == "Orchard edge copy" and (p:setChance(k2, "aster", 1) and p:chanceOf(k1, "aster") == 40))
check("a ground set can be duplicated into the player's own", p:get(p:duplicate("meadow")).builtin == false)
local keys = {}
for i = 1, p:count() do keys[p:keyAt(i)] = true end
check("every key is its own", (function() local n = 0 for _ in pairs(keys) do n = n + 1 end return n == p:count() end)())
local q = sets()
q:restore(p:serialize())
check("the player's sets come back with names, entries and order", q:count() == p:count() and q:get(k1).name == "Orchard edge" and q:chanceOf(k1, "aster") == 40 and q:keyAt(4) == k1 and q:keyAt(5) == k2)
local k3 = q:add()
check("a new key after a restore never takes an existing one", k3 ~= k1 and k3 ~= k2 and q:get(k1).name == "Orchard edge")
check("a set is removed, a ground set is not", q:remove(k1) and q:get(k1) == nil and q:indexOf(k1) == nil and not q:remove("bare") and q:get("bare") ~= nil)
check("a ground set that is not edited stays out of the file, a player's set never does", #sets():serialize() == 0 and #(function() local z = sets(); z:add(); return z:serialize() end)() == 1)
-- the table other mods read
local fakePalette = {
    findEntry = function(_, name) return name == "decoBush" and { sequential = false } or (name == "grassShort" and { sequential = true } or nil) end,
    pickInitialStage = function(_, entry) return entry.sequential and 1 or 7 end,
    getWriteName = function(_, entry, stage) return "write" .. stage end,
}
local base = sets()
base:toggle("bare", "ghost")
local api = IWFoliageSets.api(function() return base end, function() return fakePalette end, function() return 0.5 end)
check("the list gives the three ground sets with their names", #api.list() == 3 and api.list()[1].key == "meadow" and api.list()[1].name == "Meadow" and api.list()[1].builtin == true)
check("a pick is resolved to the write name and stage of the palette", (function() local r = api.pick("meadow"); return r ~= nil and r.name == "grassShort" and r.writeName == "write1" and r.stage == 1 and r.sequential == true end)())
check("a foliage the palette does not know, an empty set and an unknown set pick nothing", api.pick("bare") == nil and api.pick("forest") == nil and api.pick("nothing") == nil)
check("the entries are a copy", (function() local e = api.entries("meadow"); e[1].chance = 77; return base:chanceOf("meadow", "decoBush") == 1 end)())
-- states: a particular plant or stage of a layer
local st = sets()
st:toggle("bare", "decoBush", 4)
st:toggle("bare", "decoBush")
check("a layer and one of its states are two entries", #st:entries("bare") == 2 and st:chanceOf("bare", "decoBush", 4) == 10 and st:chanceOf("bare", "decoBush") == 10 and st:stateCount("bare", "decoBush") == 1)
st:setChance("bare", "decoBush", 30, 4)
check("a chance belongs to its entry", st:chanceOf("bare", "decoBush", 4) == 30 and st:chanceOf("bare", "decoBush") == 10 and st:addChance("bare", "decoBush", 5, 4) == 35)
local pn, ps = st:pick("bare", function() return 0.2 end)
check("a pick returns the entry's state", pn == "decoBush" and ps == 4)
pn, ps = st:pick("bare", function() return 0.4 end)
check("the layer entry has no state", pn == "decoBush" and ps == nil)
local back = sets()
back:restore(st:serialize())
check("states survive the file", back:chanceOf("bare", "decoBush", 4) == 35 and back:chanceOf("bare", "decoBush") == 10)
st:toggle("bare", "decoBush", 4)
check("taking a state out leaves the layer entry", st:chanceOf("bare", "decoBush", 4) == nil and st:chanceOf("bare", "decoBush") == 10)
local sapi = IWFoliageSets.api(function() return back end, function() return { findEntry = function() return { sequential = false } end, pickInitialStage = function() return 9 end, getWriteName = function(_, _, stage) return "w" .. stage end } end, function() return 0.2 end)
check("the published pick plants the entry's state, not a random one", sapi.pick("bare").stage == 4 and sapi.pick("bare").writeName == "w4")
print(string.format("iwfoliagesets_test: %d/%d passed", passed, passed + failed))
os.exit(failed == 0 and 0 or 1)
